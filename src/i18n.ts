// Minimal i18n: English strings are the keys, Russian translations below.
// Missing translations fall back to the English text.

export type Lang = 'ru' | 'en';

let lang: Lang = ((): Lang => {
  try {
    const saved = localStorage.getItem('webcad.lang');
    if (saved === 'ru' || saved === 'en') return saved;
  } catch {
    /* ignore */
  }
  return 'ru';
})();

export function getLang(): Lang {
  return lang;
}

export function setLang(l: Lang) {
  lang = l;
  try {
    localStorage.setItem('webcad.lang', l);
  } catch {
    /* ignore */
  }
}

