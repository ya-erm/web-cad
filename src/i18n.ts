export function t(s: string): string {
  if (lang === 'en') return s;
  return RU[s] ?? s;
}

/** Translate a word that reads differently in a context (`mate:Parallel` — a mate type, not the sketch constraint). */
export function tIn(context: string, s: string): string {
  if (lang === 'en') return s;
  return RU[`${context}:${s}`] ?? RU[s] ?? s;
}

/** Translate a feature name like "Extrude 2" keeping the counter. */
export function tName(name: string): string {
  if (lang === 'en') return name;
  const m = /^(.*?)(\s+\d+)$/.exec(name);
  if (m && RU[m[1]]) return RU[m[1]] + m[2];
  return RU[name] ?? name;
}
